const plainText = () => {
  let n = 0;
  return QUESTION_GROUPS.map(
    (g) => g.title.toUpperCase() + "\n" + g.items.map((it) => `${++n}. ${it.q}\n   (${it.why})`).join("\n")
  ).join("\n\n");
};

export default function Questions() {
  const [copied, setCopied] = useState(false);
  const total = QUESTION_GROUPS.reduce((s, g) => s + g.items.length, 0);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(
        "Брестник, ПИ 06447.28.20 — въпроси по разрешителните\n\n" + plainText()
      );
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };
  let n = 0;
  return (
    <div className="questions">
      <div className="sec-h">
        <span className="eyebrow">Към консултанта по разрешителните · {total} въпроса</span>
        <h2>Отворени въпроси</h2>
      </div>
      <p className="sub">
        По искането до РИОСВ Пловдив (Приложение № 2, ОВОС-1125-8/21.08.2026) и текущия модел: 6 къщи на ред, РЗП 1 130 м².
        Под всеки въпрос е откъде идва.
      </p>
      <button className="dims-btn" onClick={copy}>{copied ? "Копирано" : "Копирай всички като текст"}</button>
      {QUESTION_GROUPS.map((g) => (
        <div className="q-group" key={g.title}>
          <h3>{g.title}</h3>
          <ol start={n + 1}>
            {g.items.map((it) => {
              n += 1;
              return (
                <li key={n}>
                  <span className="q-text">{it.q}</span>
                  <span className="q-why">{it.why}</span>
                </li>
              );
            })}
          </ol>
        </div>
      ))}
    </div>
  );
}
